//! `cargo test` で画面向けの定数を書き出す。

use std::{env, fs, path::PathBuf};

use crate::{config, draft_keys, error_codes, events};

#[test]
fn writes_constants() {
    let export_dir = PathBuf::from(env::var("TS_RS_EXPORT_DIR").expect("TS_RS_EXPORT_DIR is set"));
    fs::create_dir_all(&export_dir).expect("could not create bindings directory");
    let action_names: Vec<String> = draft_keys::DraftAction::ALL
        .into_iter()
        .map(|action| config::choice_name(&action))
        .collect();
    let new_snippet =
        serde_json::to_string(&config::Snippet::default()).expect("could not serialize Snippet");
    let default_draft_keys = serde_json::to_string(&draft_keys::DraftKeys::default())
        .expect("could not serialize DraftKeys");
    let contents = format!(
        "// This file is generated by src-tauri/src/bindings.rs::writes_constants. Do not edit it manually.\n\
export const CONSTANTS = {{\n\
\tDEFAULT_DRAFT_FONT_SIZE: {},\n\
\tMIN_DRAFT_FONT_SIZE: {},\n\
\tMAX_DRAFT_FONT_SIZE: {},\n\
\tDEFAULT_DRAFT_HISTORY_SIZE: {},\n\
\tMAX_DRAFT_HISTORY_SIZE: {},\n\
\tDRAFT_ACTIONS: {:?},\n\
\tSUPPORTED_CODES: {:?},\n\
\tNEW_SNIPPET: {},\n\
\tDEFAULT_DRAFT_KEYS: {},\n\
\tMODIFIED_SETTINGS: {:?}\n\
}} as const;\n\n\
export const EVENTS = {{\n\
\tSETTINGS_CHANGED: {:?},\n\
\tDRAFT_HISTORY_CLEARED: {:?},\n\
\tDRAFT_HISTORY_MERGED: {:?},\n\
\tSNIPPET_ADDED: {:?},\n\
\tCONFIG_REPLACED: {:?},\n\
\tSETTINGS_CATEGORY_REQUESTED: {:?},\n\
\tSHOWN: {:?},\n\
\tHIDE_REQUESTED: {:?}\n\
}} as const;\n\n\
export const ERROR_CODES = {{\n\
\tBACKUP_RESTORE_PARTIAL: {:?},\n\
\tSETTINGS_FILE_UNREADABLE: {:?},\n\
\tSETTINGS_FOLDER_UNAVAILABLE: {:?},\n\
\tSETTINGS_ACCESS_DENIED: {:?},\n\
\tKEYS_INVALID: {:?},\n\
\tKEYS_EDITING: {:?},\n\
\tKEYS_HOTKEY: {:?},\n\
\tKEYS_ACTION_PREFIX: {:?},\n\
\tFILE_NOT_UTF8: {:?}\n\
}} as const;\n",
        config::DEFAULT_DRAFT_FONT_SIZE,
        config::MIN_DRAFT_FONT_SIZE,
        config::MAX_DRAFT_FONT_SIZE,
        config::DEFAULT_DRAFT_HISTORY_SIZE,
        config::MAX_DRAFT_HISTORY_SIZE,
        action_names,
        draft_keys::SUPPORTED_CODES,
        new_snippet,
        default_draft_keys,
        config::modified_setting_names(),
        events::SETTINGS_CHANGED,
        events::DRAFT_HISTORY_CLEARED,
        events::DRAFT_HISTORY_MERGED,
        events::SNIPPET_ADDED,
        events::CONFIG_REPLACED,
        events::SETTINGS_CATEGORY_REQUESTED,
        events::SHOWN,
        events::HIDE_REQUESTED,
        error_codes::BACKUP_RESTORE_PARTIAL,
        error_codes::SETTINGS_FILE_UNREADABLE,
        error_codes::SETTINGS_FOLDER_UNAVAILABLE,
        error_codes::SETTINGS_ACCESS_DENIED,
        error_codes::KEYS_INVALID,
        error_codes::KEYS_EDITING,
        error_codes::KEYS_HOTKEY,
        error_codes::KEYS_ACTION_PREFIX,
        error_codes::FILE_NOT_UTF8,
    );
    fs::write(export_dir.join("constants.ts"), contents).expect("could not write constants.ts");
}
